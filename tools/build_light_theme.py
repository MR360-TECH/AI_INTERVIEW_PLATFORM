"""Generates the light-theme stylesheets of the website.

    python tools/build_light_theme.py          write the files
    python tools/build_light_theme.py --check  only report whether they are up to date (the tests do this too)

The dark pages are the source of truth. For every template this reads its CSS (and the CSS of the partials it includes), asks
light_compiler.py to rewrite whatever is dark into the navy-and-light-blue light palette, and writes:

    static/css/light/base.css           shared rules (static/css/style.css) + the hand-written polish in tools/light_polish/base.css
    static/css/light/visibility.css     the shared contrast layer (static/css/visibility.css), which forces its own text colours
    static/css/light/<template>.css     that page's rules + its inline style="" attributes + tools/light_polish/<template>.css
    static/js/light-inline-map.js       inline styles marked !important (a stylesheet cannot override those, so theme.js swaps them)

Every rule is scoped to  html.light-theme , so nothing changes while the site is in dark mode.
"""
import glob
import html
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import light_compiler as LC  # noqa: E402

TEMPLATES = os.path.join(ROOT, "templates")
OUT_CSS = os.path.join(ROOT, "static", "css", "light")
OUT_MAP = os.path.join(ROOT, "static", "js", "light-inline-map.js")
POLISH = os.path.join(HERE, "light_polish")
HEADER = "/* GENERATED by tools/build_light_theme.py - do not edit by hand. */\n"
SKIP_PAGES = {"interview"}        # the live interview stays dark (immersive, proctored): no light stylesheet


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def page_names():
    return sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(TEMPLATES, "*.html"))
                  if not os.path.basename(p).startswith("_") and os.path.basename(p) != "navbar.html")


def with_partials(text, seen=None):
    """The template text plus the text of every {% include %} it pulls in (their styles and inline styles belong to the page)."""
    seen = seen or set()
    out = text
    for name in re.findall(r"\{%-?\s*include\s+['\"]([^'\"]+)['\"]", text):
        path = os.path.join(TEMPLATES, name)
        if name not in seen and os.path.exists(path):
            seen.add(name)
            out += "\n" + with_partials(read(path), seen)
    return out


def style_css(text):
    css = "\n".join(re.findall(r"<style[^>]*>(.*?)</style>", text, flags=re.S | re.I))
    css = re.sub(r"\{\{.*?\}\}", "0", css, flags=re.S)
    return re.sub(r"\{%.*?%\}", "", css, flags=re.S)


def css_string(value):
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\a ")


def inline_styles(text):
    """Returns (css rules for inline styles without !important, {original: converted} for the ones with !important)."""
    rules, important = {}, {}
    for raw in re.findall(r'\sstyle="([^"]*)"', text):
        if "{{" in raw or "{%" in raw:
            continue
        value = html.unescape(raw)
        converted, changed = [], False
        for decl in LC.split_decls(value):
            if ":" not in decl:
                converted.append(decl)
                continue
            prop, val = decl.split(":", 1)
            new = LC.transform_decl(prop, val.replace("!important", "").strip(), False)
            if new is None:
                converted.append(decl)
            else:
                changed = True
                converted.append("%s:%s%s" % (prop.strip(), new, " !important" if "!important" in val else ""))
        if not changed or value in rules or value in important:
            continue
        if "!important" in value:
            important[value] = ";".join(converted)
        else:
            body = ";".join("%s !important" % d.strip() for d in converted if d.strip() and ":" in d)
            rules[value] = 'html.light-theme [style="%s"]{%s}' % (css_string(value), body)
    return "\n".join(rules[k] for k in sorted(rules)), important


def polish(name):
    path = os.path.join(POLISH, name + ".css")
    return read(path) if os.path.exists(path) else ""


def build():
    """Returns {path: content} of every generated file."""
    files, important = {}, {}
    files[os.path.join(OUT_CSS, "base.css")] = (
        HEADER + LC.compile_light(read(os.path.join(ROOT, "static", "css", "style.css"))) + "\n" + polish("base") + "\n")
    files[os.path.join(OUT_CSS, "visibility.css")] = (
        HEADER + LC.compile_light(read(os.path.join(ROOT, "static", "css", "visibility.css"))) + "\n" + polish("visibility") + "\n")
    for name in page_names():
        if name in SKIP_PAGES:
            continue
        text = with_partials(read(os.path.join(TEMPLATES, name + ".html")))
        css = style_css(text)
        skip_root = bool(re.search(r"html\.dark-theme\s*\{", css))
        inline_css, inline_important = inline_styles(text)
        important.update(inline_important)
        files[os.path.join(OUT_CSS, name + ".css")] = (
            HEADER + LC.compile_light(css, skip_root=skip_root) + "\n" + inline_css + "\n" + polish(name) + "\n")
    files[OUT_MAP] = ("/* GENERATED by tools/build_light_theme.py - do not edit by hand. Inline styles marked !important, in their light form. */\n"
                      "window.__LIGHT_INLINE = " + json.dumps(important, sort_keys=True, ensure_ascii=False) + ";\n")
    return files


def main(argv):
    files = build()
    stale = [p for p, content in files.items() if not os.path.exists(p) or read(p) != content]
    if "--check" in argv:
        print("up to date" if not stale else "OUT OF DATE: " + ", ".join(os.path.basename(p) for p in stale))
        return 1 if stale else 0
    os.makedirs(OUT_CSS, exist_ok=True)
    for path, content in files.items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
    print("wrote %d files (%d stale before)" % (len(files), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
